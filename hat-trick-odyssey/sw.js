const PREFIX = 'hat-trick-odyssey-';
const CACHE = PREFIX + VERSION;
const SCOPE = new URL('./', self.location.href).href;
const INDEX = new URL('index.html', SCOPE).href;

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE);
    // cache: 'reload' skips the browser HTTP cache so a new version never
    // precaches stale copies. addAll is all-or-nothing: a missing file fails
    // the install and the previous version keeps running.
    await cache.addAll(FILES.map((f) => new Request(new URL(f, SCOPE).href, { cache: 'reload' })));
    await self.skipWaiting();
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const names = await caches.keys();
    await Promise.all(names.filter((n) => n.startsWith(PREFIX) && n !== CACHE).map((n) => caches.delete(n)));
    await self.clients.claim();
  })());
});

self.addEventListener('message', (event) => {
  if (event.data === 'version' && event.source) event.source.postMessage({ type: 'version', version: VERSION });
});

async function respond(request) {
  const cache = await caches.open(CACHE);
  const url = new URL(request.url);
  const isPage = request.mode === 'navigate';
  // The app is a single page: any navigation inside the scope (with or
  // without ?world=N style parameters) gets the cached shell.
  const key = isPage ? INDEX : url.origin + url.pathname;
  const hit = await cache.match(key);
  if (hit) return hit;
  try {
    const res = await fetch(request);
    // Files added after the precache list was generated still get cached on
    // first use, so they work offline next time (until the next version).
    if (res && res.ok && res.type === 'basic' && !isPage) cache.put(key, res.clone()).catch(() => {});
    return res;
  } catch (err) {
    if (isPage) {
      const shell = await cache.match(INDEX);
      if (shell) return shell;
    }
    throw err;
  }
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  if (!request.url.startsWith(SCOPE)) return; // other origins / outside the game folder: leave alone
  if (request.headers.has('range')) return;
  event.respondWith(respond(request));
});
