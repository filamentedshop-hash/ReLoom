#!/usr/bin/env node
// Regenerates the precache list inside sw.js from the real file tree.
//
//   node tools/make-precache.mjs          rewrite sw.js
//   node tools/make-precache.mjs --check  exit 1 if sw.js is out of date
//
// Re-run it whenever a file the game loads is added, removed or changed
// (the GitHub Pages workflow also runs it before every deploy). VERSION is a
// hash of the file names and contents, so it only changes when the game does.
// No dependencies beyond Node.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const swPath = path.join(root, 'sw.js');

// What ships to the player. Everything else (tools, docs, dotfiles) is skipped.
const ROOT_FILES = ['index.html', 'manifest.webmanifest', 'pwa.js'];
const DIRS = ['css', 'js', 'icons'];
const EXTENSIONS = new Set(['.html', '.css', '.js', '.mjs', '.json', '.webmanifest', '.png', '.svg', '.ico', '.jpg', '.webp', '.txt']);

function walk(dir, out) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.') || entry.name === 'node_modules') continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (entry.isFile() && EXTENSIONS.has(path.extname(entry.name).toLowerCase())) out.push(full);
  }
}

const found = [];
for (const f of ROOT_FILES) if (fs.existsSync(path.join(root, f))) found.push(path.join(root, f));
for (const d of DIRS) if (fs.existsSync(path.join(root, d))) walk(path.join(root, d), found);
const files = found.map((f) => path.relative(root, f).split(path.sep).join('/')).sort();
if (!files.includes('index.html')) { console.error('index.html not found next to sw.js'); process.exit(2); }

const hash = crypto.createHash('sha256');
for (const f of files) { hash.update(f); hash.update('\0'); hash.update(fs.readFileSync(path.join(root, f))); hash.update('\0'); }
const version = hash.digest('hex').slice(0, 12);

const block = '/* PRECACHE:BEGIN (generated by tools/make-precache.mjs, do not edit by hand) */\n' +
  `const VERSION = '${version}';\n` +
  'const FILES = [\n' + files.map((f) => `  ${JSON.stringify(f)},\n`).join('') + '];\n' +
  '/* PRECACHE:END */';

const sw = fs.readFileSync(swPath, 'utf8');
const re = /\/\* PRECACHE:BEGIN[\s\S]*?\/\* PRECACHE:END \*\//;
if (!re.test(sw)) { console.error('sw.js has no PRECACHE:BEGIN / PRECACHE:END markers'); process.exit(2); }
const next = sw.replace(re, () => block);

if (process.argv.includes('--check')) {
  if (next !== sw) { console.error('sw.js precache list is out of date: run node tools/make-precache.mjs'); process.exit(1); }
  console.log(`sw.js is up to date: version ${version}, ${files.length} files`);
} else {
  if (next !== sw) fs.writeFileSync(swPath, next);
  console.log(`${next !== sw ? 'updated' : 'unchanged'} sw.js: version ${version}, ${files.length} files`);
}
